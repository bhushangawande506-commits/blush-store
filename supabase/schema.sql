-- =============================================================================
-- 5. PAYMENTS AUDIT LOG
-- =============================================================================
-- Matches SQLite table: payments
-- IDEMPOTENCY & RETRY SAFEGUARD:
-- Scoped unique constraint on (gateway_payment_id, status) prevents duplicate entries
-- from concurrent webhooks while preserving failed historical payment attempts without
-- blocking subsequent successful retries.
CREATE TABLE IF NOT EXISTS public.payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id TEXT NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    gateway TEXT NOT NULL DEFAULT 'razorpay',
    gateway_order_id TEXT,
    gateway_payment_id TEXT,
    amount INTEGER NOT NULL CHECK (amount >= 0),
    currency TEXT NOT NULL DEFAULT 'INR',
    status TEXT NOT NULL CHECK (status IN ('pending', 'paid', 'failed', 'refunded')),
    signature_verified SMALLINT NOT NULL DEFAULT 0 CHECK (signature_verified IN (0, 1)),
    raw_response JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT uq_payments_gateway_payment_status UNIQUE (gateway_payment_id, status)
);

COMMENT ON TABLE public.payments IS 'Audit ledger of payment attempts, gateway IDs, and HMAC signature validations';

CREATE INDEX IF NOT EXISTS idx_payments_order_id ON public.payments (order_id);

-- =============================================================================
-- 6. WEBHOOKS IDEMPOTENCY LOG
-- =============================================================================
