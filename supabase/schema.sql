CREATE TABLE IF NOT EXISTS public.webhooks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id TEXT NOT NULL UNIQUE,
    event_type TEXT NOT NULL,
    payload JSONB NOT NULL,
    processed SMALLINT NOT NULL DEFAULT 1 CHECK (processed IN (0, 1)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

COMMENT ON TABLE public.webhooks IS 'Idempotency registry for Razorpay webhook events preventing duplicate processing';

CREATE UNIQUE INDEX IF NOT EXISTS idx_webhooks_event_id ON public.webhooks (event_id);

-- =============================================================================
-- 7. SECURE ATOMIC PAYMENT CONFIRMATION & INVENTORY ALLOCATION
-- =============================================================================
-- Concurrency, Idempotency & Safety Guarantees:
-- 1. SECURITY DEFINER with fixed `search_path = public, pg_temp` prevents path search hijacking.
-- 2. `FOR UPDATE` on orders serializes concurrent webhook vs. frontend verify calls.
-- 3. Rejects payment fulfillment if the order has been cancelled or refunded.
-- 4. Aggregates item quantities by `product_id` and locks product rows in ascending order
--    to prevent deadlocks, overselling, and CHECK constraint violations on multi-variant orders.
-- 5. Strict inventory check rejects fulfillment if stock is insufficient (no silent clamping to 0).
-- 6. Execution privilege: Revoked from PUBLIC, anon, and authenticated; granted exclusively to service_role.
CREATE OR REPLACE FUNCTION public.confirm_order_and_decrement_stock(
    p_order_id TEXT,
    p_razorpay_payment_id TEXT,
    p_payment_payload JSONB
)
RETURNS TABLE (success BOOLEAN, message TEXT) 
LANGUAGE plpgsql 
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_current_payment_status TEXT;
    v_current_order_status TEXT;
    v_item RECORD;
    v_prod_stock INTEGER;
    v_prod_name TEXT;
BEGIN
    -- 1. Lock the order row to serialize concurrent webhook & signature verification calls
    SELECT payment_status, order_status 
    INTO v_current_payment_status, v_current_order_status
    FROM public.orders
    WHERE id = p_order_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN QUERY SELECT false, 'Order not found';
        RETURN;
    END IF;

    -- 2. Reject fulfillment if order is cancelled or refunded
    IF v_current_order_status IN ('cancelled', 'refunded') OR v_current_payment_status = 'refunded' THEN
        RETURN QUERY SELECT false, format('Cannot process payment: order is currently %s', v_current_order_status);
        RETURN;
    END IF;

    -- 3. Idempotency Check: Exit cleanly if already marked paid (prevents duplicate stock deductions)
    IF v_current_payment_status = 'paid' THEN
        RETURN QUERY SELECT true, 'Order already confirmed paid';
        RETURN;
    END IF;

    -- 4. Pre-allocation Stock Lock & Aggregated Inventory Verification
    -- Aggregating by product_id ensures multiple line items (e.g. different sizes/colors)
    -- of the same garment are checked against total inventory, preventing overselling
    -- and CHECK constraint failures. Sorting by product_id prevents deadlocks.
    FOR v_item IN 
        SELECT product_id, SUM(quantity)::integer AS total_quantity 
        FROM public.order_items 
        WHERE order_id = p_order_id AND product_id IS NOT NULL
        GROUP BY product_id
        ORDER BY product_id
    LOOP
        SELECT stock, name INTO v_prod_stock, v_prod_name
        FROM public.products
        WHERE id = v_item.product_id
        FOR UPDATE;

        IF v_prod_stock IS NULL OR v_prod_stock < v_item.total_quantity THEN
            -- Record failed payment attempt for business audit without blocking future retries
            INSERT INTO public.payments (
                order_id, gateway, gateway_payment_id, amount, status, signature_verified, raw_response
            )
            SELECT id, 'razorpay', p_razorpay_payment_id, total_amount, 'failed', 1, p_payment_payload
            FROM public.orders WHERE id = p_order_id
            ON CONFLICT (gateway_payment_id, status) DO NOTHING;

            -- Abort fulfillment: DO NOT silently clamp stock to zero
            RETURN QUERY SELECT false, 
                format('Insufficient stock for "%s": requested %s, available %s', 
                       COALESCE(v_prod_name, 'Product ' || v_item.product_id), v_item.total_quantity, COALESCE(v_prod_stock, 0));
            RETURN;
        END IF;
    END LOOP;

    -- 5. Deduct verified aggregated stock
    FOR v_item IN 
        SELECT product_id, SUM(quantity)::integer AS total_quantity 
        FROM public.order_items 
        WHERE order_id = p_order_id AND product_id IS NOT NULL
        GROUP BY product_id
        ORDER BY product_id
    LOOP
        UPDATE public.products
        SET stock = stock - v_item.total_quantity,
            updated_at = timezone('utc'::text, now())
        WHERE id = v_item.product_id;
    END LOOP;

    -- 6. Update order to paid
    UPDATE public.orders
    SET payment_status = 'paid',
        order_status = 'paid',
        razorpay_payment_id = p_razorpay_payment_id,
        updated_at = timezone('utc'::text, now())
    WHERE id = p_order_id;

    -- 7. Audit payment entry (preserves historical attempts and logs confirmed payment)
    INSERT INTO public.payments (
        order_id, gateway, gateway_payment_id, amount, status, signature_verified, raw_response
    )
    SELECT id, 'razorpay', p_razorpay_payment_id, total_amount, 'paid', 1, p_payment_payload
    FROM public.orders
    WHERE id = p_order_id
    ON CONFLICT (gateway_payment_id, status) DO NOTHING;

    RETURN QUERY SELECT true, 'Payment verified and inventory allocated';
END;
$$;

-- Restrict execution exclusively to the trusted backend service role
REVOKE ALL ON FUNCTION public.confirm_order_and_decrement_stock(TEXT, TEXT, JSONB) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.confirm_order_and_decrement_stock(TEXT, TEXT, JSONB) FROM anon;
REVOKE ALL ON FUNCTION public.confirm_order_and_decrement_stock(TEXT, TEXT, JSONB) FROM authenticated;
GRANT EXECUTE ON FUNCTION public.confirm_order_and_decrement_stock(TEXT, TEXT, JSONB) TO service_role;

-- =============================================================================
-- 8. AUTOMATED TIMESTAMP TRIGGERS
-- =============================================================================
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER 
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_products_updated_at ON public.products;
CREATE TRIGGER trg_products_updated_at
    BEFORE UPDATE ON public.products
    FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();

DROP TRIGGER IF EXISTS trg_orders_updated_at ON public.orders;
CREATE TRIGGER trg_orders_updated_at
    BEFORE UPDATE ON public.orders
    FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();

DROP TRIGGER IF EXISTS trg_store_settings_updated_at ON public.store_settings;
CREATE TRIGGER trg_store_settings_updated_at
    BEFORE UPDATE ON public.store_settings
    FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();

