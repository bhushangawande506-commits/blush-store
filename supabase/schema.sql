COMMENT ON TABLE public.store_settings IS 'Global boutique configuration (shipping rules, contact details, boutique flags)';

-- =============================================================================
-- 2. PRODUCTS CATALOGUE
-- =============================================================================
-- Matches SQLite table: products
-- NOTE ON DATA TYPES & CONSTRAINTS:
-- - images, sizes, colors: Upgraded to JSONB for native indexing and containment queries.
-- - is_featured, is_new_arrival: Kept as SMALLINT (0, 1) to maintain 100% backward
--   compatibility with existing routes (server/routes/admin.js) without query typecasting.
-- - compare_at_price: Unconstrained relative to price to match SQLite schema and allow
--   independent price and clearance updates in server/routes/admin.js.
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    category TEXT NOT NULL,
    price INTEGER NOT NULL CHECK (price >= 0),
    compare_at_price INTEGER CHECK (compare_at_price IS NULL OR compare_at_price >= 0),
    description TEXT,
    fabric TEXT,
    care TEXT,
    images JSONB NOT NULL DEFAULT '[]'::jsonb,
    sizes JSONB NOT NULL DEFAULT '[]'::jsonb,
    colors JSONB NOT NULL DEFAULT '[]'::jsonb,
    is_featured SMALLINT NOT NULL DEFAULT 0 CHECK (is_featured IN (0, 1)),
    is_new_arrival SMALLINT NOT NULL DEFAULT 0 CHECK (is_new_arrival IN (0, 1)),
    stock INTEGER NOT NULL DEFAULT 10 CHECK (stock >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

COMMENT ON TABLE public.products IS 'Curated boutique garment inventory (Dresses, Tops, Co-ords, Skirts, Partywear)';

-- Product Performance Indexes
CREATE INDEX IF NOT EXISTS idx_products_category ON public.products (LOWER(category));
CREATE INDEX IF NOT EXISTS idx_products_slug ON public.products (slug);
CREATE INDEX IF NOT EXISTS idx_products_price ON public.products (price ASC);
CREATE INDEX IF NOT EXISTS idx_products_featured ON public.products (is_featured DESC, id ASC);
CREATE INDEX IF NOT EXISTS idx_products_new_arrival ON public.products (is_new_arrival DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_products_sizes ON public.products USING GIN (sizes);
CREATE INDEX IF NOT EXISTS idx_products_colors ON public.products USING GIN (colors);

-- =============================================================================
-- 3. ORDERS
-- =============================================================================
-- Matches SQLite table: orders
-- CRITICAL COLUMN VERIFICATION:
-- Verified against server/blush.sqlite: columns are `customer_name`, `customer_email`,
-- `customer_phone`. Preserving these names prevents breakage across server/routes/orders.js,
-- server/routes/payment.js, and src/components/CheckoutModal.jsx.
CREATE TABLE IF NOT EXISTS public.orders (
    id TEXT PRIMARY KEY, -- Preserves 'BLUSH-XXXXXX' format generated by boutique logic
    customer_name TEXT NOT NULL,
    customer_email TEXT NOT NULL,
    customer_phone TEXT NOT NULL,
    shipping_address TEXT NOT NULL,
    city TEXT NOT NULL,
    state TEXT NOT NULL,
    pincode TEXT NOT NULL,
    order_notes TEXT,
    subtotal INTEGER NOT NULL CHECK (subtotal >= 0),
    shipping_fee INTEGER NOT NULL DEFAULT 0 CHECK (shipping_fee >= 0),
    discount INTEGER NOT NULL DEFAULT 0 CHECK (discount >= 0),
    total_amount INTEGER NOT NULL CHECK (total_amount >= 0),
    payment_method TEXT NOT NULL DEFAULT 'razorpay',
    payment_status TEXT NOT NULL DEFAULT 'pending' 
        CHECK (payment_status IN ('pending', 'paid', 'failed', 'refunded')),
    order_status TEXT NOT NULL DEFAULT 'pending_payment' 
        CHECK (order_status IN ('pending_payment', 'paid', 'processing', 'shipped', 'delivered', 'cancelled')),
    razorpay_order_id TEXT,
    razorpay_payment_id TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

COMMENT ON TABLE public.orders IS 'Master boutique order ledger with customer delivery details and payment statuses';

-- Order Lookup Indexes
CREATE INDEX IF NOT EXISTS idx_orders_customer_email ON public.orders (LOWER(customer_email));
CREATE INDEX IF NOT EXISTS idx_orders_customer_phone ON public.orders (customer_phone);
CREATE INDEX IF NOT EXISTS idx_orders_razorpay_order_id ON public.orders (razorpay_order_id);
CREATE INDEX IF NOT EXISTS idx_orders_created_at ON public.orders (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_statuses ON public.orders (order_status, payment_status);

