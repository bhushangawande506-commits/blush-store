-- SCHEMA INITIALIZATION & SAFETY WARNING:
-- 1. This script uses `CREATE TABLE IF NOT EXISTS`. In PostgreSQL, `IF NOT EXISTS`
--    only creates a table if no relation by that name exists. It will NOT alter
--    columns, add constraints, or repair schema drift on previously created tables.
-- 2. This file intentionally omits destructive `DROP TABLE ... CASCADE` statements
--    to prevent accidental data loss. If applying to an environment containing
--    conflicting prototype tables, manually inspect or drop them before execution.
-- 3. All privileged mutations (order creation, stock allocation, payment audits)
--    must be executed server-side via the trusted Express backend using service_role.
